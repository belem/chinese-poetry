import { chromium } from 'playwright';
const b = await chromium.launch();
const c = await b.newContext({locale:'zh-CN'});
const p = await c.newPage();
await p.goto('https://www.shidianguji.com/zh/search/%E5%BE%A1%E8%A3%BD%E7%B7%A3%E8%AD%98', {waitUntil:'domcontentloaded'});
await p.waitForTimeout(3000);
const t = await p.evaluate(()=>document.body.innerText);
console.log(t.slice(0,1500));
const links = await p.evaluate(()=>Array.from(document.querySelectorAll('a')).map(a=>a.getAttribute('href')).filter(Boolean).slice(0,40));
console.log(JSON.stringify(links));
await b.close();
