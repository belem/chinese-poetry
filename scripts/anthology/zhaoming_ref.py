# 中段起头的注（`，韦昭曰：`）：正常底本句读是「，」，注文一律以「，某曰：」起头；
# 正文里的「，曰：」承接对话时前面没有主语，不会被这条命中。
class NoteStart(object):
    """注文起点（底本一行 = 正文 + 注，切到第一条注文之前即白文）。"""

    def search(self, s):
        cands = [m for m in (NOTE_START_ANY.search(s), NOTE_GENERIC.search(s))
                 if m and m.start() >= 1]
        ns = [m for m in NOTE_START.finditer(s) if m.start() >= 1]
        if ns:
            cands.append(ns[0])
        if cands:
            return min(cands, key=lambda m: m.start())
        return None


def lines():
    return open(REF, encoding='utf-8', errors='replace').read().split('\n')


def strip_note(s, cut=True):
    """底本一行 → 白文（切到第一条注文之前）。cut=False 时只补引号、不切注。"""
    s = re.sub(r'^["“]', '“', s.strip())
    m = NoteStart().search(s) if cut else None
    if not m:
        return s
    if m.start() <= 1:
        # 段首即注文起头（`善曰：……`）：整行是注
        return ''
    t = s[:m.start()]
    k = max(t.rfind('。'), t.rfind('，'), t.rfind('；'), t.rfind('：'))
    return t[:k + 1] if k >= 0 else t


NUM = {'一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}


def _cn2int(s):
    """卷号（逐字读）：四四 → 44，五十一 → 51，六十 → 60，十八 → 18。"""
    nums = [NUM[c] for c in s if c in NUM]
    if not nums:
        raise ValueError(s)
    t = 0
    if '十' in s:
        i = s.index('十')
        left = [NUM[c] for c in s[:i] if c in NUM]
        right = [NUM[c] for c in s[i + 1:] if c in NUM]
        return (left[0] if left else 1) * 10 + (right[0] if right else 0)
    for d in nums:
        t = t * 10 + d
    return t


VOL_HDR = re.compile(r'^卷([一二三四五六七八九十]+)\s*(.*)$')


def _blocks():
    """全文按「卷」切开：[(卷号, [行...])]，卷头行本身不进内容。"""
    out, cur = [], None
    for s in lines():
        t = s.strip()
        m = VOL_HDR.match(t) if t else None
        if m and len(t) < 20:
            cur = _cn2int(m.group(1))
            out.append((cur, []))
            continue
        if cur is not None:
            out[-1][1].append(s)
    return out


BLOCKS = None


def volume_lines(v):
    global BLOCKS
    if BLOCKS is None:
        BLOCKS = dict(_blocks())
    if v not in BLOCKS:
        raise KeyError(v)
    return BLOCKS[v]


def _para_blocks(v):
    """一卷的行块：[(kind, text)]，kind = head（篇题/作者）| para（一行白文，含注已切）。"""
    out = []
    for s in volume_lines(v):
        t = s.strip()
        if not t:
            continue
        if t.startswith('【') or t.startswith('※') or VOL_HDR.match(t):
            out.append(('head', t))
            continue
        t = strip_note(t)
        if not t:
            continue
        q = t.count('“') - t.count('”')
        if q > 0:
            t = t + '”' * q
        out.append(('para', t))
    return out


def paragraphs(v):
    """一卷底本的段落切分：[(kind, text)]，kind = head（篇题/作者）| para（自然段）。"""
    out = []
    for kind, t in _para_blocks(v):
        if not t:
            continue
        if kind == 'head':
            if t.startswith('【'):
                for mm in re.finditer(r'【([^】]*)】', t):
                    out.append(('head', '【' + mm.group(1) + '】'))
            else:
                out.append(('head', t))
            continue
        out.append(('para', t))
    return out

